    try:
        result = generator.generate(
            prompt=img['prompt'] + CLEAN_PROMPT_RULES,
            model=model_name,
            size=image_size,
            quality='standard',
            timeout=180
        )
        save_path = output_dir / f'{img["name"]}.png'
        generator.download_image(result.url, str(save_path))
        print(f'  ✅ 已保存: {save_path}')
    except Exception as e:
        print(f'  ❌ API错误: {e}')
